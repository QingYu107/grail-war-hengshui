    if (nc) extra.push('夜里做过 ' + nc + ' 次决定');
    if (f.beastDown) extra.push('砸了那块屏');
    if (f.allPresent) extra.push('七人全到场');
    return why + (extra.length ? '（' + extra.join(' · ') + '）' : '');
