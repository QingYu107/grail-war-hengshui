  /* 判序说明：
     - 许愿成真（你撑到了第七夜并开口）优先结算，否则这条线永远被兽满压掉。
     - 兽满不再是「一律满分」：你做过任何一次「不参与比较」的动作，就还有别的收场。
     - 「什么都没做」单独兜底，避免随机乱点也落到满分。 */
  function judge(s) {
    var f = s.s.flags, st = s.s;
    var wish = !!f.wishWin;

    if (wish) {
      if ((s.masterId === 'zoulijun' || s.masterId === 'zhaotiezhu') && f.wishAll) return 'E10';
      if (s.servantId === 'assassin' && st.kills === 0 && f.assassinAlive) return 'E11';
      return 'E1';
    }

    if (st.alive <= 0) return 'E2';
    if (st.exposure >= 10) return 'E3';
    if (f.doorOpen) return 'E7';
    if (f.attributed) return 'E6';

    /* 「人味」这一栏：原本只看几个固定 flag。夜里那些事（复盘、巡夜、找从者）
       和真的跟一个从者走到 LV.2，本质上是同一件事——你没有把七天全花在比较上。
       不把这两样算进来，玩家在夜里做的七次选择对结局就是零影响。 */
    var nightCount = 0;
    (function () {
      var n = st.nights || {};
      Object.keys(n).forEach(function (d) { if (n[d] !== 'sleep') nightCount++; });
    })();
    var human = f.savedRunner || f.stoodUp || f.refusedNumber || f.counterBackwards ||
                f.stayed || f.gaveUp || f.threePaths || f.erasedMarks ||
                nightCount >= 4 || (st.bond || 0) >= 2;

    if (st.beast >= 7) {
      if (f.allPresent) return 'E8';
      if (human && (f.gaveUp || f.refusedNumber || f.savedRunner)) return 'E5';
      if (human) return 'E4';
      return 'E9';
    }

    if (f.blackout && !f.powerRestored) return 'E4';
    if (f.allPresent) return 'E8';
    if (f.gaveUp && st.beast <= 2 && st.alive >= 3) return 'E5';
    if (f.didNothing || !f.summoned) return 'E2';
    if (!human) return 'E9';                       // 一次都没停下来的人，最后会变成表上的一行
    if (f.allyChen && f.metLin) return 'E5';       // 有人可投奔
    if (st.san <= 20) return 'E9';                 // 撑到最后，但已经麻了
    return 'E4';                                   // 带着人味离开
  }

  /* 判定依据：给结局页一行人能读懂的话，玩家才知道自己是怎么走到这一步的 */
