# match anchors
idx={}
for i,ln in enumerate(lines):
    m=re.match(r"^\s{10}'(.*)',?$",ln)
    if not m: continue
    c=m.group(1)
    for a,_ in INS:
        if a in c and a not in idx:
            idx[a]=i
missing=[a for a,_ in INS if a not in idx]
print("MISSING:",missing)
# build insertion map
ins_by_line={}
for a,news in INS:
    if a in idx:
        ins_by_line.setdefault(idx[a],[]).extend(news)
out=[]
for i,ln in enumerate(lines):
    out.append(ln)
    if i in ins_by_line:
        for t in ins_by_line[i]:
            out.append("          '%s',"%t)
io.open(p,"w",encoding="utf-8").write("\n".join(out))
