# -*- coding: utf-8 -*-
import io,re
p="tools/_e2new.txt"
lines=io.open(p,encoding="utf-8").read().split("\n")
DEL=[
"第一个门在主席台左边",
"他讲走廊、楼梯、食堂的窗口",
"那三秒里，礼堂顶上那台旧风扇",
"球从那个人头顶上过去",
"硬纸板上的字是马克笔写的",
"他坐在水池下面的台阶上",
"框线是黑的，格子里有数字",
]
REP=[
("坐满两千个人，会有一股味道",
 "          '坐满两千个人，会有一股味道：汗、护手霜、旧地毯。三种味道不混，一层压一层。前排是护手霜，后排是汗，靠门那一溜是地毯。',"),
("江野数过座位。",
 "          '他坐在第十七排靠过道，右脚踩在过道的黄线上，脚跟压着线，脚尖过去半寸。',"),
("所有喇叭一起打开",
 "          '所有喇叭一起打开，连澡堂里那个早就坏了的也在响。澡堂那个挂在更衣室门框上，铁皮外壳，声音是闷的，跟别的喇叭差半拍。',"),
("那一排的椅子都翻起来了",
 "          '那一排的椅子都翻起来了，翻成一排木头背。地上有一张纸屑，指甲盖那么大，是练习本的边。他弯腰捡起来，纸上没有字。',"),
("第一道铁丝网下面是松的",
 "          '第二道铁丝网缠过新的铁丝，接口朝上，他把校服外套垫在接口上，翻过去以后外套留了一个口子。',"),
("进四十七个。",
 "          '进四十七个。球是旧的，皮面起了毛，抓不住，出手的时候总要滑一下。',"),
("灯管是旧的",
 "          '灯管是旧的，一头亮一头暗，亮的那头一直嗡嗡。地上有水。',"),
("水房的墙上开始出现数字",
 "          '水房的墙上开始出现数字，一排一排，横平竖直。数字从瓷砖缝里长出来，先是一横，再是一竖。',"),
("两个男人从楼梯口上来",
 "          '两个男人从楼梯口上来。一个穿半袖，一个瘦。半袖那个手上有纹身，绕着手腕一圈。',"),
("手背上有一个印子，从昨天晚上开始发烫",
 "          '手背上有一个印子，从昨天晚上开始发烫。烫的位置在虎口往上两指，三个小点，排成一条斜线。',"),
("第二排有个女生在看手机",
 "          '第二排有个女生在看手机。屏幕调得很暗，手机压在大腿下面，只露一条边。',"),
("还有一个。第十七排靠左第四个位子",
 "          '还有一个。第十七排靠左第四个位子，有个男生低着头，在膝盖上写字。纸是从练习本上撕下来的，边上带毛刺。他写得很快，写完一行就把纸往上推一点。',"),
]
out=[]
for ln in lines:
    st=ln.strip()
    m=re.match(r"^'(.*)',?$",st)
    content=m.group(1) if m else None
    if content:
        if any(content.startswith(d) for d in DEL):
            continue
        rep=None
        for pre,new in REP:
            if content.startswith(pre):
                rep=new; break
        if rep is not None:
            out.append(rep); continue
    out.append(ln)
io.open(p,"w",encoding="utf-8").write("\n".join(out))
print("done")
