out=[]
for ln in lines:
    st=ln.strip()
    m=re.match(r"^'(.*)',?$",st)
    content=m.group(1) if m else None
    if content:
        if any(content.startswith(d) for d in DEL):
            continue
        rep=None
        for pre,new in REP:
            if content.startswith(pre):
                rep=new; break
        if rep is not None:
            out.append(rep); continue
    out.append(ln)
io.open(p,"w",encoding="utf-8").write("\n".join(out))
